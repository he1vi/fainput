android {
    namespace = "org.fcitx.fcitx5.android"

    defaultConfig {
        applicationId = "org.fcitx.fcitx5.android"
        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"

        @Suppress("UnstableApiUsage")
        externalNativeBuild {
            cmake {
                targets(
                    // jni
                    "native-lib",
                    // 【fainput / L3】llama.cpp 的 JNI（后台整理层的推理后端）
                    // 没有 llama.cpp 源码时它编为桩，但**目标必须存在** ——
                    // targets() 里写了名字却建不出来，CMake 会直接报错。
                    "native-llm",
                    // copy fcitx5 built-in addon libraries
                    "copy-fcitx5-modules",
                    // android specific modules
                    "androidfrontend",
                    "androidkeyboard",
                    "androidnotification"
                )
            }
        }
    }

    buildFeatures {
        viewBinding = true
        resValues = true
    }

    buildTypes {
        release {
            resValue("mipmap", "app_icon", "@mipmap/ic_launcher")
            resValue("mipmap", "app_icon_round", "@mipmap/ic_launcher_round")
            // fainput: 字面量而非 @string/app_name_release
            // 原因: app_name_release 在 8 个 locale 里都有定义（中文是「小企鹅输入法」），
            //       引用式会走资源解析 → 被 locale 覆盖。字面量没有 locale 变体，永远生效。
            resValue("string", "app_name", "fainPut")
            proguardFile("proguard-rules.pro")
        }
        debug {
            resValue("mipmap", "app_icon", "@mipmap/ic_launcher_debug")
            resValue("mipmap", "app_icon_round", "@mipmap/ic_launcher_round_debug")
            // fainput: 同上，debug 也用同一个名字（同包名，debug/release 不会共存）
            resValue("string", "app_name", "fainPut")
        }
    }

    androidResources {
        @Suppress("UnstableApiUsage")
        generateLocaleConfig = true
        // 【fainput / L3】模型是 .gguf —— **不要压缩**。
        // ① GGUF 本身已经压过，再压一遍只会拖慢构建、甚至变大；
        // ② 不压缩时 AssetFileDescriptor 才拿得到真实长度，
        //    解压逻辑要靠它判断"这次安装要不要重来"。
        noCompress += "gguf"
    }
}

