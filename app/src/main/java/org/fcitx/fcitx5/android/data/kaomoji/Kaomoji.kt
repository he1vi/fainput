package org.fcitx.fcitx5.android.data.kaomoji

/**
 * 【fainput / F 阶段】颜文字。
 *
 * ## 为什么是"复制到剪贴板"这条路
 *
 * 上游的符号表（`assets/.../pinyin/symbols`，6308 行）**一个颜文字都没有**
 * —— 箭头、数学、括号、全角……就是没有 `(╯°□°）╯︵ ┻━┻`。
 *
 * 而"往键盘里插"这件事上游已经有一条现成的路：**剪贴板面板**
 * （上游一直在监听系统剪贴板，我们复制进去的，面板里立刻就有）。
 *
 * ⇒ 所以这一层的做法是：挑好词 → 点一下进系统剪贴板 → 在键盘剪贴板面板里一点插入。
 * **零新增权限、零上游改动。**
 */
object Kaomoji {

    /**
     * 分组只是给人看的。
     *
     * 挑的都是**一眼能认出来**的老面孔 —— 网上那些开头十个字符都一样的
     * 长脸谱（`(っ °Д °;)っ`那类）反而不好选。
     */
    val groups: List<Pair<String, List<String>>> = listOf(
        "开心" to listOf(
            "(＾▽＾)",
            "(￣▽￣)",
            "(≧▽≦)",
            "(｡◕‿◕｡)",
            "(◕‿◕)",
            "ヽ(✿ﾟ▽ﾟ)ノ",
            "(๑˃̵ᴗ˂̵)",
            "♪(´▽｀)",
        ),
        "难过" to listOf(
            "(´；ω；`)",
            "(｡•́︿•̀｡)",
            "(╥﹏╥)",
            "(T_T)",
            "(;´Д`)",
            "(´-ω-`)",
        ),
        "无语" to listOf(
            "(╯°□°）╯︵ ┻━┻",
            "┬─┬ノ( º _ ºノ)",
            "(¬_¬)",
            "(￣ヘ￣)",
            "(눈_눈)",
            "(；一_一)",
            "¯\\_(ツ)_/¯",
        ),
        "可爱" to listOf(
            "(｡･ω･｡)",
            "ฅ(•ㅅ•❀)ฅ",
            "(=^･ω･^=)",
            "(๑•̀ㅂ•́)و✧",
            "(｀・ω・´)",
            "(o´▽`o)",
        ),
        "其它" to listOf(
            "(・_・;)",
            "(＠_＠;)",
            "(｡•̀ᴗ-)✧",
            "✧(≖ ◡ ≖✿)",
            "(๑•́ ₃ •̀๑)",
            "(っ˘ω˘ς)",
        ),
    )

    /** 全部（顺序就是上面的分组顺序）。 */
    fun all(): List<String> = groups.flatMap { it.second }
}